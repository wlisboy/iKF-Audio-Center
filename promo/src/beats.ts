/** 全局帧 → 鼓点包络 0~1（每拍起跳到 1，随后指数衰减） */
export const kick = (gframe: number): number => {
  const b = gframe / BEAT;
  const i = Math.floor(b);
  const frac = b - i;
  const raw = KICK_RAW[i] ?? 0.6;
  const s = Math.min(1, raw / 0.655);
  return s * Math.exp(-frac * 4.6);
};

/** 小节内的相对位置 0~1（每小节重置） */
export const barPhase = (gframe: number): number =>
  ((gframe % BAR) + BAR) % BAR / BAR;

/** 第 n 小节线的帧号 */
export const bar = (n: number): number => n * BAR;
